export { seedComments };
export const ensureSeedData = () => {
  if (localStorage.getItem(SEEDED_KEY)) {
    // Already seeded — dedup by seed event ID to avoid ballooning from
    // day()-relative dates. User-created events (UUIDs) pass through.
    const existing: DigEvent[] = JSON.parse(localStorage.getItem(EVENTS_KEY) || '[]');
    const seen = new Set<string>();
    const cleaned: DigEvent[] = [];
    const seedMap = new Map(seedEvents.map((e) => [e.id, e]));
    for (const e of existing) {
      if (seedMap.has(e.id)) {
        if (seen.has(e.id)) continue;
        seen.add(e.id);
        cleaned.push(seedMap.get(e.id)!);
        continue;
      }
      cleaned.push(e);
    }
    const existingIds = new Set(cleaned.map((e) => e.id));
    const missing = seedEvents.filter((e) => !existingIds.has(e.id));
    if (missing.length > 0 || cleaned.length !== existing.length) {
      localStorage.setItem(EVENTS_KEY, JSON.stringify([...cleaned, ...missing]));
    }

    // Ensure other-creator profiles exist (may not exist from earlier seeds)
    // and backfill createdAt on profiles that were seeded before the field existed
    const storedProfiles = JSON.parse(localStorage.getItem(PROFILES_KEY) || '{}');
    let profilesChanged = false;

    // Backfill createdAt on demo profile
    if (storedProfiles[DEMO_USER.id] && !storedProfiles[DEMO_USER.id].createdAt) {
      storedProfiles[DEMO_USER.id].createdAt = demoProfile.createdAt;
      profilesChanged = true;
    }

    for (const key of Object.keys(OTHER_PROFILES)) {
      if (!storedProfiles[key]) {
        storedProfiles[key] = OTHER_PROFILES[key];
        profilesChanged = true;
      } else if (!storedProfiles[key].createdAt) {
        storedProfiles[key].createdAt = OTHER_PROFILES[key].createdAt;
        profilesChanged = true;
      }
    }
    if (profilesChanged) {
      localStorage.setItem(PROFILES_KEY, JSON.stringify(storedProfiles));
    }

    // Seed comments (dedup by seed comment ID)
    const existingComments = JSON.parse(localStorage.getItem(COMMENTS_KEY) || '[]');
    const seedCommentIds = new Set(seedComments().map((c) => c.id));
    const filteredComments = existingComments.filter((c: Comment) => !seedCommentIds.has(c.id));
    localStorage.setItem(COMMENTS_KEY, JSON.stringify([...filteredComments, ...seedComments()]));

    return;
  }

  // Seed auth user
  localStorage.setItem(AUTH_KEY, JSON.stringify(DEMO_USER));

  // Seed registered users (so login works)
  const users = [{ ...DEMO_USER, password: 'demo1234' }];
  localStorage.setItem('trail-dig-users', JSON.stringify(users));

  // Seed profile
  const profiles: Record<string, UserProfile> = {};
  profiles[DEMO_USER.id] = demoProfile;
  Object.assign(profiles, OTHER_PROFILES);
  localStorage.setItem(PROFILES_KEY, JSON.stringify(profiles));

  // Seed events
  localStorage.setItem(EVENTS_KEY, JSON.stringify(seedEvents));

  // Seed comments
  localStorage.setItem(COMMENTS_KEY, JSON.stringify(seedComments()));

  localStorage.setItem(SEEDED_KEY, 'true');
};
